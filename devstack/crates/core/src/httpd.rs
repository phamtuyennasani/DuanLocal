use std::path::PathBuf;

/// macOS: prefer the system's own Apache (`/usr/sbin/httpd`, modules in
/// `/usr/libexec/apache2/`) so a fresh Mac needs nothing installed.
/// Falls back to brew httpd if the system binary is missing (rare).
const SYSTEM_HTTPD: &str = "/usr/sbin/httpd";
const SYSTEM_MODULE_DIR: &str = "/usr/libexec/apache2";

/// Generate a minimal httpd.conf that Includes our vhosts.d.
/// `ports` = every port we Listen on (global default + per-site overrides).
/// Locates Apache modules dynamically — system dir first, then brew.
pub fn write_httpd_conf(paths: &crate::paths::Paths, ports: &[u16]) -> crate::Result<()> {
    let (server_root, module_dir) = apache_layout();
    let mime_types = find_mime_types(&server_root);

    // modules we need — only include ones that exist in module_dir
    let wanted = [
        "mod_mpm_event.so",
        "mod_dir.so",
        "mod_mime.so",
        "mod_log_config.so",
        "mod_authz_core.so",
        "mod_authz_host.so",
        "mod_unixd.so",
        "mod_alias.so",
        "mod_rewrite.so",
        "mod_proxy.so",
        "mod_proxy_fcgi.so",
        "mod_ssl.so",
        "mod_socache_shmcb.so",
        "mod_setenvif.so",
        "mod_headers.so",
        "mod_negotiation.so",
        "mod_autoindex.so",
        "mod_reqtimeout.so",
        "mod_env.so",
    ];

    let mut loads = String::new();
    for m in wanted {
        let p = PathBuf::from(format!("{module_dir}/{m}"));
        if p.exists() {
            let bare = m.strip_prefix("mod_").unwrap().strip_suffix(".so").unwrap();
            loads.push_str(&format!("LoadModule {bare}_module {module_dir}/{m}\n"));
        }
    }

    // Listen on every port any site uses (dedup'd, sorted for stable output)
    let mut listens: Vec<u16> = ports.to_vec();
    listens.sort_unstable();
    listens.dedup();
    let listen_lines: String = listens
        .iter()
        .map(|p| format!("Listen 127.0.0.1:{p}\n"))
        .collect();

    let conf = format!(
        r#"# Generated by devstack — do not edit
ServerRoot "{server_root}"

{listen_lines}

{loads}
ServerName localhost

<Directory />
    AllowOverride none
    Require all denied
</Directory>

DocumentRoot "{docroot}"
<Directory "{docroot}">
    Options Indexes FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>

DirectoryIndex index.php index.html

<IfModule mime_module>
    TypesConfig {mime_types}
    AddType application/x-compress .Z
    AddType application/x-gzip .gz .tgz
</IfModule>

ErrorLog "{logs}/httpd-error.log"
LogLevel warn
<IfModule log_config_module>
    LogFormat "%h %l %u %t \"%r\" %>s %b \"%{{Referer}}i\" \"%{{User-Agent}}i\"" combined
</IfModule>

PidFile "{pid}"

# mod_proxy needs a mutex dir writable by our user — default /private/var/run is root-only
Mutex file:{run_dir} default

<IfModule unixd_module>
    User {user}
    Group {group}
</IfModule>

# devstack vhosts — Optional so an empty dir doesn't fail startup
IncludeOptional "{vhosts}/*.conf"
"#,
        server_root = server_root,
        listen_lines = listen_lines,
        loads = loads,
        docroot = paths.sites_root_default().display(),
        mime_types = mime_types,
        logs = paths.logs_dir().display(),
        pid = paths.pid_file("httpd").display(),
        run_dir = paths.run_dir().display(),
        // when run under sudo, USER=root — fall back to SUDO_USER (the real user)
        user = std::env::var("SUDO_USER")
            .ok()
            .filter(|u| u != "root" && !u.is_empty())
            .or_else(|| std::env::var("USER").ok())
            .unwrap_or_else(|| "_www".into()),
        group = if cfg!(target_os = "macos") {
            "staff"
        } else {
            "www-data"
        },
        vhosts = paths.vhosts_dir().display(),
    );

    std::fs::write(paths.httpd_conf(), conf)?;
    Ok(())
}

/// (ServerRoot, module_dir): system Apache first, brew as fallback.
fn apache_layout() -> (String, String) {
    if PathBuf::from(SYSTEM_HTTPD).exists() && PathBuf::from(SYSTEM_MODULE_DIR).is_dir() {
        return ("/usr".into(), SYSTEM_MODULE_DIR.into());
    }
    if let Some(prefix) = brew_prefix() {
        let root = format!("{prefix}/opt/httpd");
        let modules = format!("{root}/lib/httpd/modules");
        if PathBuf::from(&modules).is_dir() {
            return (root, modules);
        }
    }
    // last resort — system paths even if binary missing; conf gen still works
    ("/usr".into(), SYSTEM_MODULE_DIR.into())
}

/// mime.types ships in /etc/apache2 on macOS; brew keeps it under conf/.
fn find_mime_types(server_root: &str) -> String {
    for candidate in [
        format!("{server_root}/conf/mime.types"),
        "/etc/apache2/mime.types".to_string(),
    ] {
        if PathBuf::from(&candidate).exists() {
            return candidate;
        }
    }
    "/etc/apache2/mime.types".into()
}

pub fn brew_prefix() -> Option<String> {
    if PathBuf::from("/opt/homebrew/bin/brew").exists() {
        Some("/opt/homebrew".into())
    } else if PathBuf::from("/usr/local/bin/brew").exists() {
        Some("/usr/local".into())
    } else {
        which::which("brew").ok().and_then(|p| {
            p.parent()
                .and_then(|p| p.parent())
                .map(|p| p.display().to_string())
        })
    }
}

/// httpd binary — system first (zero install), brew as fallback.
pub fn httpd_bin() -> Option<PathBuf> {
    let sys = PathBuf::from(SYSTEM_HTTPD);
    if sys.exists() {
        return Some(sys);
    }
    let prefix = brew_prefix()?;
    let p = PathBuf::from(format!("{prefix}/opt/httpd/bin/httpd"));
    p.exists().then_some(p)
}

pub fn start_httpd(paths: &crate::paths::Paths) -> crate::Result<()> {
    let httpd = httpd_bin().ok_or_else(|| crate::Error::Config("httpd not found".into()))?;
    crate::service::spawn_daemon(
        httpd.to_str().unwrap(),
        &["-f", paths.httpd_conf().to_str().unwrap(), "-k", "start"],
        &paths.pid_file("httpd"),
        &paths.log_file("httpd"),
    )?;
    Ok(())
}

pub fn stop_httpd(paths: &crate::paths::Paths) -> crate::Result<()> {
    crate::service::stop_daemon(&paths.pid_file("httpd"), 5)
}
